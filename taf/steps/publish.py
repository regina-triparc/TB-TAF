"""
The end of the automation half: a person approves, then the spec and the Xray
test cases are committed to `qa/<TICKET>` in the test repository, pushed, and a
pull request is opened.

    approval_gate   pauses the graph (LangGraph `interrupt`) until someone approves
                    or rejects: `python -m taf resume <run_id> --approve`, or the
                    dashboard. Not asked when nothing would leave the machine.
    publish         deterministic and idempotent. Re-running it after a crash or a
                    resume finds the commit already made, the branch already pushed
                    and the PR already open, and does nothing twice.

Only reached when the static validation passed. A Playwright run that failed does
not block the PR - it may be a real defect - but the PR is opened as a draft and
says so.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from langgraph.types import interrupt

from taf.agents.base import agent_node
from taf.agents.state import QAState
from taf.config import SETTINGS
from taf.core.text import utc_now
from taf.integrations.github.pr_api import PullRequestClient, PullRequestError
from taf.integrations.github.repository import REPO_LOCK, TEST_REPO, CommandError
from taf.integrations.jira import xray
from taf.llm.router import ROUTER
from taf.steps.context import append_log


def has_output(state: QAState) -> bool:
    """Is there anything to publish (offline placeholders never are)?"""
    if ROUTER.resolve(state.get("llm_provider")) == "offline":
        return False
    return bool(state.get("generated_typescript_code") or xray.ticket_files(state))


def approval_not_needed(state: QAState) -> Optional[str]:
    """Why no approval is asked for this run, or None when it must be."""
    if not has_output(state):
        return "nothing to publish"
    if not SETTINGS.require_approval:
        return "REQUIRE_APPROVAL=false"
    if SETTINGS.no_git:
        return "in-place mode: files stay uncommitted in the working copy"
    if not SETTINGS.git_push_enabled and not SETTINGS.pr_create_enabled:
        return "GIT_PUSH_ENABLED=false and PR_CREATE_ENABLED=false: the commit stays in the local clone"
    return None


def approval_request(state: QAState) -> Dict[str, Any]:
    """What the approver sees (dashboard, CLI, interrupt payload)."""
    validation = state.get("validation") or {}
    review = state.get("review") or {}
    return {
        "ticket_id": state["ticket_id"],
        "spec": f"{SETTINGS.test_spec_dir.strip('/')}/{state['ticket_id']}.spec.ts",
        "branch": f"qa/{state['ticket_id']}",
        "will_push": SETTINGS.git_push_enabled,
        "will_open_pr": SETTINGS.pr_create_enabled,
        "validation_ok": bool(validation.get("ok")),
        "playwright_passed": bool(state.get("execution_passed")),
        "review_findings": [f"{f['severity']}: {f['rule']} - {f['detail']}" for f in review.get("findings") or []],
    }


@agent_node("Approval Gate", engine="human", abort_on_error=False, span_type="guardrail")
def approval_gate(state: QAState) -> Dict[str, Any]:
    current = state.get("approval") or {}
    if current.get("status") in {"approved", "rejected"}:
        return {}
    reason = approval_not_needed(state)
    if reason:
        return {"approval": {"status": "not_required", "note": reason, "at": utc_now()}}
    # Pauses the run here; the checkpoint keeps everything until a decision arrives.
    decision = interrupt(approval_request(state))
    if not isinstance(decision, dict):
        decision = {"approved": bool(decision)}
    approved = bool(decision.get("approved"))
    return {"approval": {"status": "approved" if approved else "rejected",
                         "by": str(decision.get("by") or "unknown")[:100],
                         "note": str(decision.get("note") or "")[:500], "at": utc_now()}}


def pr_body(state: QAState, files: List[str]) -> str:
    validation = state.get("validation") or {}
    review = state.get("review") or {}
    passed = bool(state.get("execution_passed"))
    lines = [
        f"AI-generated end-to-end tests for **{state['ticket_id']}**: {state.get('summary', '')}",
        "",
        "> Generated by the TB-TAF QA agent. Review like any other change: the tests passing is not "
        "proof that they cover the acceptance criteria.",
        "",
        "### Files",
        *[f"- `{f}`" for f in files],
        "",
        "### Validation (mandatory, passed)",
        *[f"- {'skipped' if c.get('skipped') else 'ok' if c.get('ok') else 'FAILED'}: {c['name']}"
          for c in validation.get("checks") or []],
        "",
        "### Playwright",
        "All generated tests passed against the target environment." if passed else
        "**Some tests failed or did not run** against the target environment - this PR is a draft. "
        "A failure may be a real defect or a wrong test; check the run log.",
    ]
    findings = review.get("findings") or []
    if findings:
        lines += ["", "### Review findings", *[f"- **{f['severity']}** {f['rule']}: {f['detail']}" for f in findings]]
    approval = state.get("approval") or {}
    lines += ["", f"Run `{state['run_id']}`"
              + (f" · approved by {approval.get('by')}" if approval.get("status") == "approved" else "")
              + (f" · [trace]({state['trace_url']})" if state.get("trace_url") else "")]
    return "\n".join(lines)


@agent_node("Publisher", engine="git", abort_on_error=False, span_type="tool")
def publish(state: QAState) -> Dict[str, Any]:
    ticket_id = state["ticket_id"]
    record: Dict[str, Any] = dict(state.get("publish") or {})
    if not has_output(state):
        return {"publish": {**record, "skipped": "nothing to publish"}}
    if not (state.get("validation") or {}).get("ok"):
        return {"publish": {**record, "skipped": "mandatory validation failed"}}
    if (state.get("approval") or {}).get("status") not in {"approved", "not_required"}:
        return {"publish": {**record, "skipped": "not approved"}}

    logs: List[str] = []
    errors: List[str] = []
    code = state.get("generated_typescript_code") or ""
    with REPO_LOCK:
        try:
            TEST_REPO.ensure_ready(logs)
            branch = TEST_REPO.prepare_branch(ticket_id, logs)
            spec, xray_paths = TEST_REPO.write_ticket_files(ticket_id, code, xray.ticket_dir(ticket_id),
                                                            xray.ticket_files(state), logs)
            paths = ([spec] if spec else []) + xray_paths
            root = TEST_REPO.path.resolve() if TEST_REPO.path else None
            rel = [p.resolve().relative_to(root).as_posix() for p in paths] if root else []
            record.update({"branch": branch, "files": rel})
            if SETTINGS.no_git:
                record.update({"committed": False, "pushed": False, "note": "in-place mode: left uncommitted"})
            else:
                sha, created = TEST_REPO.commit(ticket_id, paths, logs)
                record.update({"commit_sha": sha, "committed": True, "new_commit": created})
                record["pushed"] = TEST_REPO.push(branch, logs) if SETTINGS.git_push_enabled else False
                if not SETTINGS.git_push_enabled:
                    logs.append("[info] GIT_PUSH_ENABLED=false - commit kept in the local clone, not pushed.")
                elif not record["pushed"]:
                    errors.append(f"Publisher: push of {branch} failed - see the log; no pull request opened.")
        except CommandError as exc:
            if exc.result is not None:
                logs.append(exc.result.as_log())
            logs.append(f"[error] {exc}")
            errors.append(f"Publisher: {exc}")

    if record.get("pushed") and SETTINGS.pr_create_enabled:
        try:
            title = f"test({ticket_id}): AI-generated Playwright spec and Xray test cases"
            draft = not state.get("execution_passed")
            pr = PullRequestClient().ensure_pull_request(record["branch"], title,
                                                         pr_body(state, record.get("files") or []), draft)
            record.update({"pr_url": pr.url, "pr_number": pr.number, "pr_created": pr.created, "pr_draft": pr.draft})
            logs.append(f"[info] pull request {'opened' if pr.created else 'already open'}: {pr.url}")
        except PullRequestError as exc:
            errors.append(f"Publisher: {exc}")
    elif record.get("pushed"):
        logs.append("[info] PR_CREATE_ENABLED=false - branch pushed, no pull request opened.")

    update: Dict[str, Any] = {"publish": record, "execution_logs": append_log(state, logs),
                              "git_branch": record.get("branch", ""), "git_pushed": bool(record.get("pushed")),
                              "xray_files": [f for f in record.get("files") or [] if not f.endswith(".spec.ts")]}
    if errors:
        update["errors"] = errors
    return update
